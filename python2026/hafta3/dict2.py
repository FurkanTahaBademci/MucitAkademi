isimler = {"furkan", "ahmet", "ayşe"}

isimler.add("mehmet")  # Yeni bir eleman ekledik
print(isimler)  # Güncellenmiş küme içeriğini yazdırdık
isimler.remove("ahmet")  # Bir elemanı kaldırdık
print(isimler)  # Güncellenmiş küme içeriğini yazdırdık
isimler.discard("ayşe")  # Bir elemanı güvenli bir şekilde kaldırdık
print(isimler)  # Güncellenmiş küme içeriğini yazdırdık
isimler.clear()  # Kümedeki tüm elemanları kaldırdık
print(isimler)  # Güncellenmiş küme içeriğini yazdırdık