my_string = "Hello, World! "

print("Original:", my_string)
print("Upper:",my_string.upper())  # tüm harfleri büyük yapar
print("Lower:",my_string.lower())  # tüm harfleri küçük yapar
print("Capitalize:",my_string.capitalize())  # sadece ilk harfi büyük yapar
print("Title:",my_string.title())  # her kelimenin ilk harfini büyük yapar
print("Swapcase:",my_string.swapcase())  # büyük harfleri küçük, küçük harfleri büyük yapar
print("Strip:",my_string.strip())  # baştaki ve sondaki boşlukları kaldırır